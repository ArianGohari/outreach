import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export function renderGoogleClient(raw) {
  if (Buffer.byteLength(raw) > 65536) throw new Error('OAuth configuration is too large.');
  let config;
  try {
    config = JSON.parse(raw)?.installed;
  } catch {
    throw new Error('Invalid OAuth JSON.');
  }
  if (
    !config ||
    typeof config.client_id !== 'string' ||
    !/^[A-Za-z0-9_-]+\.apps\.googleusercontent\.com$/.test(config.client_id) ||
    config.client_id.length > 1024 ||
    typeof config.client_secret !== 'string' ||
    !/^[A-Za-z0-9_-]+$/.test(config.client_secret) ||
    config.client_secret.length > 4096
  ) throw new Error('A Google Desktop app OAuth client is required.');
  // Include only the public desktop client, never tokens, accounts or supplied URLs.
  return `// Code generated by scripts/configure-google.mjs; DO NOT EDIT.\npackage googlemail\n\nfunc init() {\n\tbundledClient = clientConfig{ID: ${JSON.stringify(config.client_id)}, Secret: ${JSON.stringify(config.client_secret)}}\n}\n`;
}

export function configureGoogle(raw, output, required) {
  // A failed configuration must not leave a stale client in a later build.
  rmSync(output, { force: true });
  if (!raw) {
    if (required) throw new Error('GOOGLE_OAUTH_CLIENT_JSON is required for release builds.');
    return false;
  }
  writeFileSync(output, renderGoogleClient(raw), { mode: 0o600 });
  return true;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const args = process.argv.slice(2);
    const file = args.find(arg => !arg.startsWith('--'));
    const raw = file ? readFileSync(file, 'utf8') : process.env.GOOGLE_OAUTH_CLIENT_JSON;
    const output = fileURLToPath(new URL('../internal/googlemail/client_build.go', import.meta.url));
    const configured = configureGoogle(raw, output, args.includes('--required'));
    console.log(configured ? 'Google desktop client configured for this build.' : 'No bundled Google client; local developer configuration remains available.');
  } catch {
    console.error('Could not configure Google OAuth. Supply a valid Desktop app JSON using a file path or GOOGLE_OAUTH_CLIENT_JSON.');
    process.exitCode = 1;
  }
}
